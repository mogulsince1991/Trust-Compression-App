const assert = require("node:assert/strict");
const fs = require("node:fs");
const vm = require("node:vm");
const ts = require("typescript");
const code = ts.transpileModule(fs.readFileSync("lib/journey-appearance.ts", "utf8"), { compilerOptions: { module: ts.ModuleKind.CommonJS } }).outputText;
const context = { exports: {}, URL };
vm.runInNewContext(code, context);
const { normalizeAppearance, appearanceColors } = context.exports;
assert.equal(normalizeAppearance({ headerLogoUrl: "javascript:alert(1)" }).headerLogoUrl, "");
assert.equal(normalizeAppearance({ alignment: "left", font: "geometric" }).alignment, "left");
assert.equal(normalizeAppearance({ font: "geometric" }).font, "geometric");
assert.equal(normalizeAppearance({ gradientEnd: "url(evil)" }).gradientEnd, "#faa916");
assert.equal(normalizeAppearance({ googleTagId: "<script>" }).googleTagId, "");
assert.equal(normalizeAppearance({ googleTagId: "G-ABC123" }).googleTagId, "G-ABC123");
assert.equal(normalizeAppearance({ metaPixelId: "123456789" }).metaPixelId, "123456789");
assert.equal(normalizeAppearance({ metaPixelId: "abc" }).metaPixelId, "");
assert.equal(context.exports.journeyAssetTitleKey({ id: "new-row", libraryAssetId: "stable-asset" }), "stable-asset");
assert.equal(normalizeAppearance({ titleOverrides: { stable: "  Custom title  " } }).titleOverrides.stable, "Custom title");
const pageSource = fs.readFileSync("components/journey-viewer.tsx", "utf8");
assert.doesNotMatch(pageSource.slice(pageSource.indexOf("function landingCard"), pageSource.indexOf("function landingCard") + 1100), /asset\.summary|asset\.note/);
assert.equal(normalizeAppearance().branding, "none");
assert.equal(normalizeAppearance().journeyType, "collection");
assert.equal(normalizeAppearance({ journeyType: "landing" }).journeyType, "landing");
assert.equal(normalizeAppearance({ journeyType: "invalid" }).journeyType, "collection");
assert.equal(normalizeAppearance({ calendarUrl: "javascript:alert(1)" }).calendarUrl, "");
const landing = normalizeAppearance({ journeyType: "landing", preparationSteps: "First\nSecond", resourcesHeading: "Your questions", calendarUrl: "https://example.com/calendar" });
assert.deepEqual(normalizeAppearance(JSON.parse(JSON.stringify(landing))), landing);
assert.equal(landing.preparationSteps, "First\nSecond");
assert.equal(normalizeAppearance({ confirmationLabel: "x".repeat(200) }).confirmationLabel.length, 120);
assert.equal(normalizeAppearance({ branding: "unknown" }).branding, "none");
assert.equal(normalizeAppearance({ logoUrl: "javascript:alert(1)" }).logoUrl, "");
assert.equal(normalizeAppearance({ websiteUrl: "https://user:password@example.com" }).websiteUrl, "");
assert.equal(normalizeAppearance({ logoUrl: "https://example.com/logo.png" }).logoUrl, "https://example.com/logo.png");
assert.equal(normalizeAppearance({ background: "url(evil)" }).background, "#171b18");
assert.equal(appearanceColors(normalizeAppearance({ theme: "light" })).background, "#f5f5f1");
assert.equal(appearanceColors(normalizeAppearance({ theme: "custom", background: "#123456" })).background, "#123456");
assert.equal(normalizeAppearance({ showContents: false }).showContents, false);
for (const file of ["app/share/[token]/page.tsx", "app/embed/journey/[token]/page.tsx"]) assert.match(fs.readFileSync(file, "utf8"), /appearance: row.appearance/);
assert.match(fs.readFileSync("components/journey-viewer.tsx", "utf8"), /appearance.branding === "trusttale"/);
assert.match(fs.readFileSync("app/api/workspaces/[id]/appearance/route.ts", "utf8"), /requireWorkspaceManager\(await requireWorkspaceAccess/);
console.log("Journey appearance checks passed.");
const editor = fs.readFileSync("components/sage-journeys.tsx", "utf8");
assert.match(editor, /onSave\(published\)/);
assert.match(editor, /published \? "Save changes"/);
assert.doesNotMatch(editor, /onSave\(true\); setStep/);
assert.match(editor, /saveError \? <p role="alert"/);
assert.doesNotMatch(fs.readFileSync("components/journey-viewer.tsx", "utf8"), /var\(--font-geist-sans\)/);
const appearanceEditor = fs.readFileSync("components/journey-appearance-editor.tsx", "utf8");
assert.match(appearanceEditor, /theme: "custom", background: colors.background/);
assert.doesNotMatch(appearanceEditor, /disabled=/);
assert.match(fs.readFileSync("components/trust-app-ingestion.tsx", "utf8"), /assets: contentChanged \?/);
console.log("Published editing, color controls, font fallback and metadata-only save checks passed.");
