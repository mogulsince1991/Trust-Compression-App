// Isolated UI contract tests. All application and CRM requests are intercepted;
// this script never signs into or writes to the production database.
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const base = process.env.TEST_BASE_URL || 'http://127.0.0.1:3120';
if (!['localhost', '127.0.0.1'].includes(new URL(base).hostname)) throw new Error('Run against a local app only.');
const out = path.resolve('artifacts/sage-studio');
fs.mkdirSync(out, { recursive: true });
const workspaces = [{ id: 'workspace-a', name: 'Northline Remodeling', role: 'owner' }, { id: 'workspace-b', name: 'Second company', role: 'owner' }];
const thumbnail = 'data:image/svg+xml,' + encodeURIComponent('<svg xmlns="http://www.w3.org/2000/svg" width="640" height="360"><rect width="640" height="360" fill="#bacdb5"/><path d="M140 270V170L320 65l180 105v100H140" fill="#eff1e8"/><path d="M320 65L140 170M320 65l180 105" stroke="#5c946e" stroke-width="12"/><rect x="290" y="185" width="60" height="85" fill="#668875"/><rect x="190" y="185" width="55" height="45" fill="#a1b49a"/><rect x="395" y="185" width="55" height="45" fill="#a1b49a"/></svg>');
const videos = ['A kitchen designed around real life', 'What your roofing estimate includes', 'Meet the team behind your project', 'A homeowner shares their experience'].map((title, i) => ({ id: `video-${i}`, title, source_platform: 'youtube', source_url: `https://youtube.com/watch?v=fixture${i}`, embed_url: `https://youtube.com/embed/fixture${i}`, thumbnail_url: thumbnail, duration_seconds: 142 + i * 40, summary: 'A project story that answers the questions buyers ask before choosing a contractor.', tags: ['project proof', 'roofing'], metadata: {}, created_at: '2026-09-01' }));
const asset = { id: 'document-1', workspace_id: 'workspace-a', asset_type: 'document', source_platform: 'google_docs', title: 'Your project planning guide', source_url: 'https://docs.google.com/document/d/fixture', embed_url: 'https://docs.google.com/document/d/fixture/preview', summary: 'What to expect before, during, and after your project.' };
let journeys = [];
const requests = [];
async function run() {
  const browser = await chromium.launch({ headless: true, ...(process.env.TEST_BROWSER_CHANNEL ? { channel: process.env.TEST_BROWSER_CHANNEL } : {}) });
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
  await context.route('**/*', async route => {
    const req = route.request(), url = new URL(req.url());
    const json = body => route.fulfill({ contentType: 'application/json', body: JSON.stringify(body) });
    if (url.hostname.endsWith('supabase.co')) {
      if (url.pathname.includes('/auth/')) return json({ id: 'fixture-user', email: 'fixture@example.test' });
      if (url.pathname.endsWith('/videos')) return json(url.searchParams.get('workspace_id') === 'eq.workspace-b' ? [] : videos);
      if (url.pathname.endsWith('/rpc/ensure_workspace')) return json('workspace-a');
      return json([]);
    }
    if (url.origin !== new URL(base).origin) return route.abort();
    if (!url.pathname.startsWith('/api/') && !url.pathname.startsWith('/mcp')) return route.continue();
    requests.push({ url: url.pathname + url.search, method: req.method(), body: req.postDataJSON() });
    if (url.pathname === '/api/workspaces') return json({ workspaces });
    if (url.pathname === '/api/library-assets') return json({ assets: url.searchParams.get('workspaceId') === 'workspace-b' ? [] : [asset] });
    if (url.pathname === '/api/journey-contacts') return json({ contacts: [{ id: 'crm-1', contactRecordId: 'contact-1', name: 'Alice Example', sourceLabel: 'JobTread' }, { id: 'crm-2', contactRecordId: 'contact-2', name: 'Bob Example', sourceLabel: 'HighLevel' }] });
    if (url.pathname.endsWith('/send')) {
      if (req.postDataJSON().contactId === 'contact-2') return route.fulfill({ status: 500, contentType: 'application/json', body: JSON.stringify({ error: 'Test contact link failure' }) });
      return json({ shareUrl: base + '/share/alice-only' });
    }
    if (url.pathname === '/api/journeys' || /^\/api\/journeys\/journey-/.test(url.pathname)) {
      if (req.method() !== 'GET') {
        const body = req.postDataJSON();
        const row = { ...body, id: 'journey-1', shareUrl: base + '/share/fixture', isPublic: body.publish === true, publishedAt: body.publish ? '2026-09-13' : null, assets: body.assets.map((a, i) => ({ ...a, id: 'asset-' + i, position: i + 1 })), videoIds: body.assets.map(a => a.videoId).filter(Boolean) };
        journeys = [row]; return json({ id: row.id, shareUrl: row.shareUrl });
      }
      return json({ journeys: url.searchParams.get('workspaceId') === 'workspace-b' ? [] : journeys, folders: [] });
    }
    if (url.pathname === '/api/connect/accounts') return json({ accounts: [{ id: 'account-a', provider: 'jobtread', label: 'JobTread', status: 'connected' }] });
    if (url.pathname === '/api/metrics/contractor/config') return json({ ruleSets: [] });
    return json({ contacts: [], profiles: [], links: [], events: [], identities: [], members: [], invites: [], keys: [], isAdmin: false });
  });
  await context.addInitScript(() => {
    localStorage.setItem('sb-boswlaonbdxugkocquzv-auth-token', JSON.stringify({ access_token: 'fixture.ui.only', token_type: 'bearer', refresh_token: 'fixture', expires_at: Math.floor(Date.now() / 1000) + 3600, expires_in: 3600, user: { id: 'fixture-user', email: 'fixture@example.test', aud: 'authenticated' } }));
    if (!localStorage.getItem('trusttale-appearance')) localStorage.setItem('trusttale-appearance', 'light');
  });
  const page = await context.newPage();
  const errors = []; page.on('pageerror', err => errors.push(err.message));
  page.on('dialog', dialog => dialog.accept());
  page.setDefaultTimeout(20000);
  page.setDefaultNavigationTimeout(120000);
  await page.goto(base + '/app/library');
  await page.getByRole('heading', { name: 'Library', exact: true }).waitFor();
  await page.getByRole('button', { name: /A kitchen designed/ }).click();
  await page.screenshot({ path: path.join(out, 'desktop-library-light.png'), fullPage: true });
  await page.getByRole('combobox', { name: 'Appearance' }).selectOption('dark');
  await page.screenshot({ path: path.join(out, 'desktop-library-dark.png'), fullPage: true });
  await page.emulateMedia({ colorScheme: 'light' });
  assert.equal(await page.locator('html').getAttribute('data-sage-theme'), 'dark', 'Explicit theme must ignore system changes');
  await page.getByRole('combobox', { name: 'Appearance' }).selectOption('light');
  await page.getByRole('button', { name: 'Back to library', exact: true }).click();
  await page.getByRole('textbox', { name: 'Search library' }).fill('no-such-content');
  await page.getByRole('heading', { name: 'No matching content' }).waitFor();
  assert.equal(await page.getByRole('button', { name: 'Add your first content' }).count(), 0);
  await page.getByRole('button', { name: 'Clear search and filters' }).click();
  await page.getByRole('checkbox', { name: 'Select A kitchen designed around real life' }).check();
  await page.getByRole('checkbox', { name: 'Select Your project planning guide' }).check();
  await page.getByRole('button', { name: 'Create journey', exact: true }).click();
  await page.getByRole('button', { name: '2 Details' }).click();
  await page.getByLabel('Internal name').fill('Roofing buyer proof');
  await page.getByLabel('Buyer-facing headline').fill('A closer look at your project');
  await page.getByRole('link', { name: 'Library', exact: true }).click();
  await page.getByRole('button', { name: 'Continue journey (2)' }).click();
  await page.getByRole('heading', { name: 'Roofing buyer proof', exact: true }).waitFor();
  await page.reload();
  await page.getByRole('heading', { name: 'Roofing buyer proof', exact: true }).waitFor();
  await page.getByRole('button', { name: 'Save draft', exact: true }).click();
  await page.getByRole('status').filter({ hasText: 'Private draft saved.' }).waitFor();
  assert.equal(journeys[0].isPublic, false);
  await page.getByRole('button', { name: 'Publish journey', exact: true }).click();
  await page.getByLabel('General journey link').waitFor();
  assert.equal(journeys[0].isPublic, true);
  await page.getByRole('button', { name: 'Alice Example JobTread' }).click();
  await page.getByRole('button', { name: 'Create personalized link', exact: true }).click();
  await page.getByLabel('Personalized link', { exact: true }).waitFor();
  assert((await page.getByLabel('General journey link').inputValue()).endsWith('/share/fixture'));
  await page.getByRole('button', { name: 'Bob Example HighLevel' }).click();
  await page.getByRole('button', { name: 'Create personalized link', exact: true }).click();
  await page.getByRole('alert').filter({ hasText: 'Test contact link failure' }).waitFor();
  assert.equal(await page.getByLabel('Personalized link', { exact: true }).count(), 0, 'Failed generation must not show another recipient link');
  await page.getByRole('button', { name: 'Dismiss message' }).click();
  await page.screenshot({ path: path.join(out, 'desktop-sharing.png'), fullPage: true });
  await page.getByRole('combobox', { name: 'Current workspace' }).selectOption('workspace-b');
  await page.getByRole('link', { name: 'Library', exact: true }).click();
  await page.getByRole('heading', { name: 'Your first piece of proof starts here' }).waitFor();
  await page.getByRole('combobox', { name: 'Current workspace' }).selectOption('workspace-a');
  await page.getByRole('button', { name: /A kitchen designed/ }).waitFor();
  await page.getByRole('link', { name: 'Reports', exact: true }).click();
  await page.getByRole('button', { name: 'Connections', exact: true }).click();
  await page.getByText('Connected accounts (1)', { exact: true }).waitFor();
  assert(requests.some(r => r.url === '/api/connect/accounts?workspaceId=workspace-a'));
  await page.screenshot({ path: path.join(out, 'desktop-reports.png'), fullPage: true });
  await page.getByRole('button', { name: 'Settings', exact: true }).click();
  await page.screenshot({ path: path.join(out, 'desktop-settings.png'), fullPage: true });
  await page.getByRole('button', { name: 'Content sources', exact: true }).click();
  await page.screenshot({ path: path.join(out, 'desktop-sources.png'), fullPage: true });
  await page.getByRole('link', { name: 'Home', exact: true }).click();
  await page.screenshot({ path: path.join(out, 'desktop-home.png'), fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.getByRole('button', { name: 'Library', exact: true }).click();
  await page.screenshot({ path: path.join(out, 'mobile-library-light.png'), fullPage: true });
  assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'Mobile layout must not overflow');
  await page.getByRole('button', { name: /A kitchen designed/ }).click();
  await page.screenshot({ path: path.join(out, 'mobile-preview-light.png'), fullPage: true });
  assert.equal(await page.locator('.sage-library-main').isVisible(), false, 'Preview gets the full mobile screen');
  await page.getByRole('combobox', { name: 'Appearance' }).selectOption('dark');
  await page.screenshot({ path: path.join(out, 'mobile-preview-dark.png'), fullPage: true });
  await page.getByRole('button', { name: 'Journeys', exact: true }).click();
  await page.getByRole('button', { name: 'Edit journey', exact: true }).click();
  await page.screenshot({ path: path.join(out, 'mobile-editor-dark.png'), fullPage: true });
  const footer = await page.locator('.sage-editor-footer').boundingBox();
  const row = await page.locator('.sage-sequence-row').last().boundingBox();
  assert(footer.y >= row.y + row.height, 'Action footer must never cover an asset row');
  await page.getByRole('button', { name: 'Journeys', exact: true }).click();
  await page.getByRole('button', { name: 'Manage archive', exact: true }).click();
  await page.getByRole('heading', { name: 'Manage archive' }).waitFor();
  assert(requests.some(r => r.url === '/api/archive?workspaceId=workspace-a'));
  await page.screenshot({ path: path.join(out, 'mobile-archive.png'), fullPage: true });
  assert.deepEqual(errors, [], 'No browser runtime errors');
  const signedOut = await browser.newContext({ viewport: { width: 390, height: 844 } });
  const authPage = await signedOut.newPage();
  await authPage.goto(base + '/app/home');
  await authPage.getByRole('heading', { name: 'Welcome back' }).waitFor();
  await authPage.screenshot({ path: path.join(out, 'mobile-signin.png'), fullPage: true });
  await authPage.getByRole('button', { name: 'Sign in with an email link instead' }).click();
  assert.equal(await authPage.getByLabel('Password', { exact: true }).count(), 0);
  await signedOut.close();
  fs.writeFileSync(path.join(out, 'results.json'), JSON.stringify({ passed: true, tests: ['mixed media library', 'light/dark/system preference', 'empty search', 'draft survives navigation and reload', 'private save payload', 'explicit publish', 'workspace isolation', 'report workspace and connections tab', 'mobile preview and overflow'], requestCount: requests.length, errors }, null, 2));
  console.log('Sage Studio UI smoke checks passed. Screenshots: ' + out);
  await browser.close();
}
run().catch(err => { console.error(err); process.exit(1); });
