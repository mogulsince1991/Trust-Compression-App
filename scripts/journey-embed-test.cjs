const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const source = fs.readFileSync('public/trusttale-embed.js', 'utf8');
const origin = 'https://app.trusttale.co';
const calls = [];
function frame(src) { return { src, style: {}, contentWindow: { postMessage: (...args) => calls.push(args) } }; }
const first = frame(origin + '/embed/journey/one');
const second = frame(origin + '/embed/journey/two');
const foreign = frame('https://other.example/embed/journey/one');
const unrelated = frame(origin + '/app/home');
const frames = [first, second, foreign, unrelated];
let listener;
let listeners = 0;
const window = { addEventListener: (name, fn) => { assert.equal(name, 'message'); listener = fn; listeners++; } };
const context = vm.createContext({ window, URL, document: { currentScript: { src: origin + '/trusttale-embed.js' }, querySelectorAll: () => frames } });
vm.runInContext(source, context);
assert.equal(calls.length, 2);
function send(overrides = {}) { listener({ origin, source: first.contentWindow, data: { type: 'trusttale:resize', version: 1, height: 850 }, ...overrides }); }
send({ origin: 'https://evil.example' });
send({ source: foreign.contentWindow });
send({ source: unrelated.contentWindow });
assert.equal(first.height, undefined);
send();
assert.equal(first.height, '850');
assert.equal(second.height, undefined);
send({ source: second.contentWindow });
assert.equal(second.height, '850');
for (const height of [NaN, Infinity, '900']) send({ data: { type: 'trusttale:resize', version: 1, height } });
assert.equal(first.height, '850');
send({ data: { type: 'trusttale:resize', version: 1, height: 999999 } });
assert.equal(first.height, '4000');
send({ data: { type: 'trusttale:resize', version: 1, height: -10 } });
assert.equal(first.height, '320');
vm.runInContext(source, context);
assert.equal(listeners, 1);
const dynamic = frame(origin + '/embed/journey/three');
frames.push(dynamic);
send({ source: dynamic.contentWindow, data: { type: 'trusttale:ready', version: 1 } });
assert.equal(calls.at(-1)[0].type, 'trusttale:init');
console.log('Embed origin/source validation, independent frames, height bounds, dynamic handshake and duplicate loading passed.');
