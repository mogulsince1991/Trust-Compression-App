const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const ts = require('typescript');
const api = {};
const code = ts.transpileModule(fs.readFileSync('lib/server/workspace-photo-storage.ts', 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 } }).outputText;
vm.runInNewContext(code, { exports: api, Buffer, Date, URLSearchParams, AbortSignal, process: { env: { STORAGE_CREDENTIAL_KEY: 'test-only' } }, require: name => name === './route-auth' ? { httpError: (status,message) => Object.assign(Error(message), { status }) } : require(name) });
const encrypted = api.sealStorage({ refreshToken: 'private' }, 'workspace-a');
assert.equal(api.openStorage(encrypted, 'workspace-a').refreshToken, 'private');
assert.ok(!encrypted.includes('private'));
assert.throws(() => api.openStorage(encrypted, 'workspace-b'));
const pieces = encrypted.split('.');
pieces[2] = Buffer.from('tampered').toString('base64url');
assert.throws(() => api.openStorage(pieces.join('.'), 'workspace-a'));
for (const role of ['owner','admin','member','sales_rep','library_manager']) assert.equal(api.canUploadPhotos(role),true);
for (const role of ['viewer','unknown','']) assert.throws(() => api.requirePhotoWriter({ workspaceRole: role }), { status:403 });
const source = fs.readFileSync('app/api/workspace-storage/upload/route.ts','utf8');
assert.ok(!source.includes('.storage.from('));
console.log('Workspace storage encryption, tenant binding, and role checks passed.');
