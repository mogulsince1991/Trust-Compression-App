const fs = require('node:fs');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const ts = require('typescript');
const source = ts.transpileModule(fs.readFileSync('lib/playback-clock.ts', 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2020 } }).outputText;
const moduleExports = {};
vm.runInNewContext(source, { exports: moduleExports });
const { PlaybackClock } = moduleExports;
const clock = new PlaybackClock();
let now = 0;
const sample = (position, options = {}) => clock.sample({ position, duration: 100, playing: true, visible: true, rate: 1, now: now += 1000, ...options });
sample(0, { playing: false }); sample(0, { playing: false });
assert.equal(clock.secondsWatched, 0, 'loading does not count');
sample(0); sample(1); sample(2);
assert.equal(clock.secondsWatched, 2);
sample(2, { playing: false }); sample(2, { playing: false });
assert.equal(clock.secondsWatched, 2, 'pause does not count');
sample(2); sample(2); sample(2);
assert.equal(clock.secondsWatched, 2, 'buffering does not count');
sample(80); sample(81);
assert.equal(clock.secondsWatched, 3, 'seek excludes skipped seconds');
assert.equal(clock.snapshot().percentWatched, 3);
sample(82, { visible: false }); sample(90, { visible: false }); sample(91); sample(92);
assert.equal(clock.secondsWatched, 4, 'hidden playback excluded');
clock.resetSample(); sample(0); sample(1); sample(2);
assert.equal(clock.secondsWatched, 6, 'revisiting accumulates viewing time');
assert.equal(clock.snapshot().percentWatched, 4, 'replays do not inflate unique coverage');
clock.resetSample(); sample(10, { rate: 2 }); sample(12, { rate: 2 });
assert.equal(clock.secondsWatched, 7, '2x playback counts actual time');
assert.equal(clock.snapshot().percentWatched, 6, '2x covers two seconds of content');
sample(90, { now: now + 60000 });
assert.equal(clock.secondsWatched, 7, 'suspended polling does not invent watch time');
clock.resetSample(); sample(20); sample(21, { playing: false });
assert.equal(clock.secondsWatched, 8, 'pause flush preserves last second');
clock.sample({ position: NaN, duration: 0, playing: true, visible: true, rate: 1, now: 0 });
assert.equal(clock.secondsWatched, 8, 'invalid provider samples ignored');
const viewer = fs.readFileSync('components/journey-viewer.tsx', 'utf8');
assert(!viewer.includes('client_timer'));
assert(!viewer.includes('onLoad={() => setStarted(true)}'));
assert(!viewer.includes('durationSeconds) * 1000'));
assert(viewer.includes('keepalive: true'));
console.log('Playback clock tests passed: loading, pause, buffer, seek, hidden tab, replay, speed, suspend, final flush, invalid samples.');
